export const adventureQuestions: Question[] = rows.flatMap((stage, s) =>
  stage.map((r, i) => {
    const [
      en,
      zh,
      answer,
      distractors,
      slide,
      explanation,
      type = "choice",
      audio,
    ] = r;
    return {
      id: `s${s + 1}-${i < 5 ? "text" : "ext"}-${(i % 5) + 1}`,
      stageId: s + 1,
      type,
      difficulty: s === 5 ? "B1" : "A2",
      sourceType: i < 5 ? "textbook" : "extension",
      sourceSlide: slide,
      learningObjective: zh,
      questionEnglish: en,
      questionChinese: zh,
      ...(distractors.length ? { options: [answer, ...distractors] } : {}),
      correctAnswer: answer,
      explanationChinese: explanation,
      vocabularyNotes: vocabulary
        .filter((v) =>
          (en + " " + answer).toLowerCase().includes(v.word.toLowerCase()),
        )
        .map((v) => `${v.word}: ${v.zh}`),
      referenceText:
        type === "listening"
          ? undefined
          : slide >= 2 && slide <= 5
            ? reading.find((p) => p.slide === slide)?.en
            : slide >= 8 && slide <= 10
              ? conversation
                  .filter((l) => l.slide === slide)
                  .map((l) => `${l.speaker}: ${l.en}`)
                  .join("\n")
              : undefined,
      ...(audio ? { audioText: audio } : {}),
    } as Question;
  }),
);
